// Appends the 12 triangles of an axis-aligned box to an ASCII STL stream.
void box(std::ostringstream& o, double x0, double y0, double z0, double x1, double y1, double z1) {
    const double v[8][3] = {{x0, y0, z0}, {x1, y0, z0}, {x1, y1, z0}, {x0, y1, z0},
                            {x0, y0, z1}, {x1, y0, z1}, {x1, y1, z1}, {x0, y1, z1}};
    // Each face: normal + two triangles (counter-clockwise seen from outside).
    struct Face {
        double n[3];
        int a, b, c, d;
    };
    const Face faces[6] = {{{0, 0, -1}, 0, 3, 2, 1}, {{0, 0, 1}, 4, 5, 6, 7}, {{0, -1, 0}, 0, 1, 5, 4},
                           {{0, 1, 0}, 2, 3, 7, 6},  {{-1, 0, 0}, 0, 4, 7, 3}, {{1, 0, 0}, 1, 2, 6, 5}};
    auto tri = [&](const double* n, int i, int j, int k) {
        o << "  facet normal " << n[0] << ' ' << n[1] << ' ' << n[2] << "\n    outer loop\n";
        for (int idx : {i, j, k}) o << "      vertex " << v[idx][0] << ' ' << v[idx][1] << ' ' << v[idx][2] << "\n";
        o << "    endloop\n  endfacet\n";
    };
    for (const auto& f : faces) {
        tri(f.n, f.a, f.b, f.c);
        tri(f.n, f.a, f.c, f.d);
    }
}

bool cmdExamples(const std::string& dir) {
    // Finned bar, 100 mm x 20 mm x 10 mm base with four 2 mm x 20 mm x 15 mm fins. Units: metres.
    std::ostringstream stl;
    stl.precision(6);
    stl << "solid heatsink_bar\n";
    box(stl, 0.0, 0.0, 0.0, 0.100, 0.020, 0.010);
    for (int i = 0; i < 4; ++i) {
        const double x = 0.010 + i * 0.025;
        box(stl, x, 0.0, 0.010, x + 0.002, 0.020, 0.025);
    }
    stl << "endsolid heatsink_bar\n";

    // SYNTHETIC nodal field (not an ANSYS export): the analytical rod solution sampled on a
    // cylinder of cross-section A = 1e-4 m^2 (radius 5.642 mm), 41 stations x 9 nodes.
    const wb::RodProblem p;
    const double r = std::sqrt(p.area_m2 / kPi);
    std::ostringstream csv;
    csv << "# SYNTHETIC DATA - generated by wb_cli examples, NOT an actual ANSYS export.\n"
        << "# T(x) = 100 - 80x + 500x(1-x) degC (L=1 m, k=10 W/(m K), q=1e4 W/m^3); uniform over each cross-section.\n"
        << "# Units: coordinates in metres, temperature in degrees Celsius. Licence: CC0 (self-created).\n"
        << "node_id,x_m,y_m,z_m,temperature_C\n";
    int id = 1;
    for (int s = 0; s <= 40; ++s) {
        const double x = p.length_m * s / 40.0;
        const double T = wb::exactTemperature(p, x);
        csv << id++ << ',' << formatNumber(x, 8) << ",0,0," << formatNumber(T, 10) << "\n";
        for (int k = 0; k < 8; ++k) {
            const double a = 2 * kPi * k / 8.0;
            csv << id++ << ',' << formatNumber(x, 8) << ',' << formatNumber(r * std::cos(a), 8) << ','
                << formatNumber(r * std::sin(a), 8) << ',' << formatNumber(T, 10) << "\n";
        }
    }
    return writeFile(dir + "/heatsink_bar.stl", stl.str()) &&
           writeFile(dir + "/synthetic_rod_nodal_temperatures.csv", csv.str());
}

// ---------------- Task C ----------------

bool cmdFea(const std::string& dir) {
    const wb::RodProblem p;
    const int meshes[] = {10, 20, 40, 80};
    const char* colors[] = {"#dc2626", "#ea580c", "#16a34a", "#2563eb"};

    std::ostringstream nodal, conv;
    nodal << "elements,node,x_m,T_fe_C,T_exact_C,abs_error_C\n";
    conv << "elements,h_m,max_nodal_error_C,max_midpoint_error_C,predicted_qh2_over_8k_C,observed_order\n";

    std::vector<wb::Series> profile;
    {
        wb::Series ex{"exact", {}, {}, "#111827", false, true};
        for (int i = 0; i <= 200; ++i) {
            const double x = p.length_m * i / 200.0;
            ex.x.push_back(x);
            ex.y.push_back(wb::exactTemperature(p, x));
        }
        profile.push_back(ex);
    }
    wb::Series errSeries{"FE midpoint max error", {}, {}, "#2563eb", false, false};
    wb::Series errPts{"computed", {}, {}, "#2563eb", true, false};
    wb::Series refSeries{"q h^2/(8k) (theory)", {}, {}, "#9ca3af", false, true};

    wb::ErrorReport prev{};
    for (int i = 0; i < 4; ++i) {
        const int n = meshes[i];
        const auto s = wb::solveRod(p, n);
        const auto e = wb::computeErrors(p, s);
        for (int j = 0; j <= n; ++j)
            nodal << n << ',' << j << ',' << formatNumber(s.x_m[j]) << ',' << formatNumber(s.T_C[j]) << ','
                  << formatNumber(wb::exactTemperature(p, s.x_m[j])) << ','
                  << formatNumber(std::abs(s.T_C[j] - wb::exactTemperature(p, s.x_m[j]))) << "\n";
        const double predicted = p.q_W_m3 * e.h_m * e.h_m / (8 * p.k_W_mK);
        conv << n << ',' << formatNumber(e.h_m) << ',' << formatNumber(e.maxNodalError_C) << ','
             << formatNumber(e.maxMidpointError_C) << ',' << formatNumber(predicted) << ','
             << (i ? formatNumber(wb::observedOrder(prev, e), 6) : std::string("")) << "\n";
        std::printf("  N=%-3d h=%.5f  max nodal err=%.3e  max midpoint err=%.6f C\n", n, e.h_m, e.maxNodalError_C,
                    e.maxMidpointError_C);
        prev = e;

        wb::Series fe{"FE N=" + std::to_string(n), s.x_m, s.T_C, colors[i], n <= 20, false};
        profile.push_back(fe);
        errSeries.x.push_back(e.h_m);
        errSeries.y.push_back(e.maxMidpointError_C);
        refSeries.x.push_back(e.h_m);
        refSeries.y.push_back(predicted);
    }
    errPts.x = errSeries.x;
    errPts.y = errSeries.y;

    wb::PlotSpec ps{"Rod temperature: FE (N=10..80) vs exact", "x [m]", "Temperature [degC]"};
    wb::PlotSpec cs{"Mesh convergence (slope 2 on log-log)", "element size h [m]", "max |T_FE - T_exact| at midpoints [degC]",
                    true, true};
    return writeFile(dir + "/fea_nodal_temperatures.csv", nodal.str()) &&
           writeFile(dir + "/fea_convergence.csv", conv.str()) &&
           writeFile(dir + "/fea_temperature_profiles.svg", wb::renderSvg(ps, profile)) &&
           writeFile(dir + "/fea_convergence.svg", wb::renderSvg(cs, {refSeries, errSeries, errPts}));
}

// ---------------- Task D ----------------

bool cmdBench(const std::string& dir, const wb::BatchConfig& cfg) {
    const auto si = wb::querySystemInfo();
    std::printf("  CPU: %s | %d physical / %d logical | RAM %.1f GiB\n", si.cpuName.c_str(), si.physicalCores,
                si.logicalCpus, si.ramGiB);
    std::printf("  workload: %d cases x %d elements, seed %llu, %d reps + 1 warm-up\n", cfg.cases, cfg.elements,
                static_cast<unsigned long long>(cfg.seed), cfg.repetitions);
    const auto rep = wb::runBenchmark(cfg, nullptr, [](double f, const std::string& ph) {
        std::fprintf(stderr, "\r  %5.1f%%  %-28s", 100 * f, ph.c_str());
    });
    std::fprintf(stderr, "\n");

    std::ostringstream raw, sum, env;
    raw << "mode,workers,repetition,seconds\n";
    sum << "mode,workers,median_s,speedup_T1_over_Tp,efficiency,max_abs_diff_vs_serial_C\n";
    auto rows = [&](const std::string& mode, const wb::WorkerTiming& t) {
        for (std::size_t i = 0; i < t.seconds.size(); ++i)
            raw << mode << ',' << t.workers << ',' << i + 1 << ',' << formatNumber(t.seconds[i], 9) << "\n";
        sum << mode << ',' << t.workers << ',' << formatNumber(t.median, 9) << ',' << formatNumber(t.speedup, 6) << ','
            << formatNumber(t.efficiency, 6) << ',' << formatNumber(t.maxAbsDiffVsSerial, 6) << "\n";
    };
    rows("serial", rep.serial);
    for (const auto& t : rep.pool) {
        rows("pool", t);
        std::printf("  pool %d worker(s): median %.4f s  speedup %.2f  efficiency %.2f  max|diff| %.1e C\n", t.workers,
                    t.median, t.speedup, t.efficiency, t.maxAbsDiffVsSerial);
    }
    std::printf("  serial loop:      median %.4f s   agreement %s\n", rep.serial.median, rep.agreementOk ? "OK" : "FAILED");

    env << "cpu," << si.cpuName << "\nphysical_cores," << si.physicalCores << "\nlogical_cpus," << si.logicalCpus
        << "\nram_GiB," << formatNumber(si.ramGiB, 4) << "\nos," << si.os << "\ncompiler," << si.compiler
        << "\noptimisation_flags," << si.optFlags << "\nseed," << cfg.seed << "\ncases," << cfg.cases
        << "\nelements_per_case," << cfg.elements << "\nwarmup_runs,1\nmeasured_repetitions," << cfg.repetitions
        << "\nagreement_tolerance_C,1e-8\nagreement_ok," << (rep.agreementOk ? "true" : "false") << "\n";

    wb::Series ideal{"ideal (speedup = p)", {}, {}, "#9ca3af", false, true};
    wb::Series meas{"measured", {}, {}, "#2563eb", false, false};
    wb::Series pts{"median of reps", {}, {}, "#2563eb", true, false};
    for (const auto& t : rep.pool) {
        ideal.x.push_back(t.workers);
        ideal.y.push_back(t.workers);
        meas.x.push_back(t.workers);
        meas.y.push_back(t.speedup);
    }
    pts.x = meas.x;
    pts.y = meas.y;
    wb::PlotSpec sp{"Batch speedup T1/Tp (" + std::to_string(cfg.cases) + " cases x " + std::to_string(cfg.elements) +
                        " elements)",
                    "worker threads p", "speedup T1/Tp [-]"};
    return writeFile(dir + "/bench_raw_timings.csv", raw.str()) && writeFile(dir + "/bench_summary.csv", sum.str()) &&
           writeFile(dir + "/bench_environment.csv", env.str()) &&
           writeFile(dir + "/bench_speedup.svg", wb::renderSvg(sp, {ideal, meas, pts}));
}

